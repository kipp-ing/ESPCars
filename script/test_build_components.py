#!/usr/bin/env python3
"""Compose upstream-style component fixtures and validate or compile them.

config includes validate.* fixtures; compile (also --only-generate) selects only
test*.yaml by default. Explicit validate.* fixtures cannot be compiled.
Generated wrappers and distinct per-config builds live under .esphome/.
"""

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]


def list_targets(*, include_validate=False, root=None):
    root = ROOT if root is None else root
    directory = root / "tests/components"
    patterns = ["*/test*.yaml"]
    if include_validate:
        patterns.append("*/validate*.yaml")
    return sorted(
        path.relative_to(root).as_posix()
        for pattern in patterns
        for path in directory.glob(pattern)
    )


def target_parts(target):
    """Return component, variant and platform, rejecting arbitrary input paths."""
    path = Path(target)
    if path.parts[:2] != ("tests", "components") or len(path.parts) != 4:
        raise ValueError(
            f"Expected tests/components/<component>/<fixture>.yaml: {target}"
        )
    match = re.fullmatch(
        r"((?:test|validate)(?:-[\w-]+)?)\.(esp32(?:-c[36])?-idf)\.yaml", path.name
    )
    if match is None or re.fullmatch(r"[a-z][a-z0-9_]*", path.parent.name) is None:
        raise ValueError(f"Unsupported component fixture: {target}")
    return path.parent.name, *match.groups()


def node_name(target):
    component, variant, platform = target_parts(target)
    variant = variant.replace("validate", "v", 1).removeprefix("test").strip("-")
    name = "-".join(
        part for part in (component, variant, platform.removesuffix("-idf")) if part
    ).replace("_", "-")
    # ESPHome hostnames are limited to 31 characters. Keep long future fixture
    # names deterministic and collision-resistant rather than merely truncating.
    if len(name) > 31:
        name = name[:22] + "-" + hashlib.sha256(name.encode()).hexdigest()[:8]
    return name


def build_path(target, *, root=None):
    root = ROOT if root is None else root
    return root / ".esphome/build" / node_name(target)


def compose(target, *, root=None):
    """Write one deterministic wrapper using package vars, shared by every caller."""
    root = ROOT if root is None else root
    component, _, platform = target_parts(target)
    fixture = root / target
    base = (
        root / "tests/test_build_components" / f"build_components_base.{platform}.yaml"
    )
    if not fixture.is_file() or not base.is_file():
        raise ValueError(f"Missing component fixture or platform base: {target}")
    output = root / ".esphome/test_build_components" / f"{node_name(target)}.yaml"
    output.parent.mkdir(parents=True, exist_ok=True)
    variables = {
        "node_name": node_name(target),
        "component_build_path": str(build_path(target, root=root)),
        "component_test_file": str(fixture),
        "component_dir": str(fixture.parent),
        "repo_root": str(root),
    }
    # The include tag is ESPHome-specific; safe_dump handles all variable values,
    # including checkout paths containing spaces, quotes or YAML punctuation.
    content = (
        "# Generated by script/test_build_components.py; do not edit.\n"
        "packages:\n  base: !include\n    file: "
        + yaml.safe_dump(str(base), default_style='"').strip()
        + "\n    vars:\n"
        + "".join(
            "      " + line + "\n" for line in yaml.safe_dump(variables).splitlines()
        )
    )
    if not output.is_file() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8")
    return output


def compile_command(target):
    return f"python script/test_build_components.py compile {target}"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "command", choices=("config", "compile"), nargs="?", default="compile"
    )
    parser.add_argument(
        "targets",
        nargs="*",
        help="Component fixture paths; default: all for this command",
    )
    parser.add_argument("--list-targets", action="store_true")
    parser.add_argument(
        "--only-generate",
        action="store_true",
        help="Generate C++ without compiling (compile only)",
    )
    args = parser.parse_args(argv)
    if args.only_generate and args.command != "compile":
        parser.error("--only-generate requires compile")
    targets = args.targets or list_targets(include_validate=args.command == "config")
    if not targets:
        parser.error("No component fixtures found")
    try:
        names = [node_name(target) for target in targets]
        if len(names) != len(set(names)):
            raise ValueError("Component fixtures must have distinct node names")
        for target in targets:
            if args.command == "compile" and Path(target).name.startswith("validate"):
                raise ValueError(f"Config-only fixture cannot be compiled: {target}")
            target_parts(target)
        if args.list_targets:
            print("\n".join(targets))
            return 0
        for target in targets:
            output = compose(target)
            print(f"{args.command.upper()} {target}", flush=True)
            command = [sys.executable, "-m", "esphome", args.command, str(output)]
            if args.only_generate:
                command.append("--only-generate")
            result = subprocess.run(command, cwd=ROOT, check=False)
            if result.returncode:
                return result.returncode
    except (OSError, ValueError) as error:
        parser.exit(2, f"{error}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
