#!/usr/bin/env python3
"""Generate root CODEOWNERS from literal component/platform owner lists.

Matches upstream's component-level union for flat platforms and separate rules
for directory platforms. Preserve the repository's existing catch-all owner;
component ownership always comes from CODEOWNERS declarations, never a guess.
"""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = """# Generated by script/build_codeowners.py; do not edit by hand.
# The catch-all preserves the former .github/CODEOWNERS repository policy.
* @kipp-ing

# Components (owners declared in their Python modules)
"""


def owners_from(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "CODEOWNERS"
            for target in node.targets
        ):
            owners = ast.literal_eval(node.value)
            if not isinstance(owners, list) or any(
                not isinstance(owner, str)
                or not owner.startswith("@")
                or any(char.isspace() for char in owner)
                for owner in owners
            ):
                raise ValueError(f"{path.name}: CODEOWNERS must be a list of @owners")
            return owners
    return []


def generate(root: Path) -> str:
    rules: dict[str, list[str]] = {}
    for hub in sorted((root / "components").glob("*/__init__.py")):
        owners = owners_from(hub)
        if not owners:
            raise ValueError(f"components/{hub.parent.name}: missing CODEOWNERS list")
        pattern = f"/components/{hub.parent.name}/*"
        rules[pattern] = owners
        for source in sorted(hub.parent.iterdir()):
            if source == hub:
                continue
            if source.is_dir() and (source / "__init__.py").is_file():
                platform_owners = owners_from(source / "__init__.py")
                if platform_owners:
                    rules[f"/components/{hub.parent.name}/{source.name}/*"] = (
                        platform_owners
                    )
            elif source.suffix == ".py":
                rules[pattern].extend(owners_from(source))
    lines = [HEADER.rstrip()]
    for pattern, owners in sorted(rules.items()):
        lines.append(f"{pattern} {' '.join(sorted(set(owners), key=str.casefold))}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        expected = generate(args.root)
    except (ValueError, SyntaxError) as error:
        print(error)
        return 1
    path = args.root / "CODEOWNERS"
    if args.check:
        if (args.root / ".github" / "CODEOWNERS").exists():
            print(".github/CODEOWNERS shadows root CODEOWNERS; remove the shadow file")
            return 1
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            print("CODEOWNERS is stale or missing; run script/build_codeowners.py")
            return 1
        print("CODEOWNERS: 0 findings (up to date)")
    else:
        path.write_text(expected, encoding="utf-8")
        print("Wrote CODEOWNERS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
